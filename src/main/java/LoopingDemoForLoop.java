public class LoopingDemoForLoop {
    public static void main(String[] args) {
        //calling static method-class name.method name
        LoopingDemoForLoop.forDemo();
    }
    public static void forDemo() {

        for (int i = 0; i < 10; i++) {
            System.out.println("Akhil Jain "+i);
        }
    }
}

